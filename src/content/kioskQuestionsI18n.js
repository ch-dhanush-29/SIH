export function getQuestionText(qObj, langCode) {
  if (!qObj) return "";
  if (qObj.q_i18n && qObj.q_i18n[langCode]) {
    return qObj.q_i18n[langCode];
  }
  // Legacy / fallback mappings
  if (langCode === "hi" && qObj.qHi) return qObj.qHi;
  if (langCode === "bn" && qObj.qBn) return qObj.qBn;
  return qObj.q || "";
}

export function getOptionLabels(qObj, langCode) {
  if (!qObj) return [];
  if (qObj.options_i18n && qObj.options_i18n[langCode]) {
    return qObj.options_i18n[langCode];
  }
  return qObj.options || [];
}

export function getConditionLabel(conditionId, langCode) {
  const item = CONDITION_LABELS[conditionId];
  if (!item) return conditionId;
  return item[langCode] || item.en || conditionId;
}
